#!/usr/bin/env python3
"""Rank Sunnyside Environmental against other PPS schools on utilization, enrollment
trend, forecast, neighborhood capture rate, special-education share and spending.
Writes SUNNYSIDE_RANKINGS.md at the repo root. All inputs are district documents in this repo."""
import glob, os, re, statistics

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = lambda *a: os.path.join(ROOT, *a)
TARGET = "Sunnyside"


def norm(name):
    n = re.sub(r"(E\.S\.|M\.S\.|H\.S\.|\bP?K-8\b|\bSchool\b|\bEnvironmental\b|\bElementary\b|\bProgram\b|\bK8\b|\bMS\b|\bES\b|\bHS\b)", "", name)
    return re.sub(r"[^a-z]", "", n.lower())


def read(path):
    return open(path, encoding="utf-8", errors="ignore").read()


# 1. Utilization, 2025-26 (BoardBook 2026-04-20 engagement-session report)
util = {}
txt = re.sub(r"[ \t]+", " ", read(glob.glob(P("boardbook", "2026-04-20_*", "District_2025-26_Enrollment__Utilization_*.txt"))[0]))
pat = re.compile(r"([A-Z][\w.'’ /&-]*?) (K-5|K-8|PK-8|MS|HS|2-8|K-12|6-12) "
                 r"(Neighborhood / Immersion|Neighborhood / Focus Option|Focus Option / Alternative|Neighborhood|Alternative)"
                 r"( Title I)? (\d+) (\d+)(?: (\d+)%)?")
for m in pat.finditer(txt):
    name, typ, prog, t1, enr, cap, pct = m.groups()
    util[norm(name)] = dict(name=name.strip(), type=typ, program=prog, title1=bool(t1), enr=int(enr), cap=int(cap),
                            pct=round(100 * int(enr) / int(cap)))  # computed; the PDF text drops some % cells

# 2. Neighborhood capture rate, Oct 2025
capture = {}
for line in read(P("program-docs", "2025-10_PPS-neighborhood-capture-rate-2025-26.txt")).splitlines():
    m = re.match(r"^\s*E?([A-Z][\w.'’ /&-]+?)\s{2,}([\d,]+)\s+(\d+)%", line)
    if m and "Total" not in m.group(1):
        capture[norm(m.group(1))] = (m.group(1).strip(), int(m.group(3)))

# 3. Ten-year enrollment history (2016-17 .. 2025-26)
hist = {}
for line in read(P("program-docs", "2025-10_PPS-enrollment-10yr-history-detail-by-school-2025-26.txt")).splitlines():
    m = re.match(r"^\s*([A-Za-zÀ-ÿ][\w.'’ /&-]+?)\s{2,}(?:\([\d, ]+\)\s+)?(?:[A-Z]{1,2}-\d+|\d+-\d+)\s+((?:[\d,]+\s+){10})", line)
    if m:
        vals = [int(v.replace(",", "")) for v in m.group(2).split()]
        if len(vals) == 10 and vals[-1] > 50:
            hist.setdefault(norm(m.group(1)), (m.group(1).strip(), vals))
district_hist = None
for line in read(P("program-docs", "2025-10_PPS-enrollment-10yr-history-detail-by-school-2025-26.txt")).splitlines():
    if line.strip().startswith("Total"):
        vals = [int(v.replace(",", "")) for v in re.findall(r"\d{1,2},\d{3}", line)][:10]
        if len(vals) == 10 and (district_hist is None or vals[0] > district_hist[0]):
            district_hist = vals  # grand total = the largest "Total" row

# 4. PSU Population Research Center forecast (2026 edition), program "Total" rows
fc = {}
for line in read(P("program-docs", "2026_PSU-PRC-PPS-enrollment-forecast-2026-27-to-2035-36.txt")).splitlines():
    m = re.match(r"^\s*([A-Z][\w.'’ /&-]+?)\s{2,}(ES|K8|MS|HS|K12)\s+Total\s+\S+\s+((?:[\d,]+\s+){12}[\d,]+)", line)
    if m:
        vals = [int(v.replace(",", "")) for v in m.group(3).split()]
        fc[norm(m.group(1))] = (m.group(1).strip(), m.group(2), vals)  # 2023-24 .. 2035-36

# 5. Underserved groups (special education share), Oct 2025
sped = {}
for line in read(P("program-docs", "2025-10_PPS-enrollment-of-underserved-groups-2025-26.txt")).splitlines():
    m = re.match(r"^([A-Z][\w.'’ /&-]+?)\s{2,}(\d+)\s+(\d+)\s+([\d.]+)\s+(\d+)\s+([\d.]+)\s+(\d+)\s+([\d.]+)", line)
    if m:
        sped.setdefault(norm(m.group(1)), (m.group(1).strip(), int(m.group(2)), float(m.group(6)), float(m.group(8))))  # enr, DC%, SpEd%

# 6. Dollars per student (latest year in the 2027 school reports)
cost = {}
for line in read(glob.glob(P("boardbook", "2026-04-28_*", "2027_SCHOOL_REPORTS_Volume_2_*.txt"))[0]).splitlines():
    m = re.match(r"^\s*([A-Z][\w.'’ /&-]+?)\s{2,}\d+%\s+\d+%\s+(?:[\d.]+\s+){4,5}((?:\$[\d,]+\s+){4,5})", line)
    if m:
        cost.setdefault(norm(m.group(1)), (m.group(1).strip(), int(m.group(2).split()[-1].strip("$").replace(",", ""))))


def rank(d, key, value_of, reverse=True, filt=lambda k: True):
    items = [(k, value_of(v)) for k, v in d.items() if filt(k) and value_of(v) is not None]
    items.sort(key=lambda kv: kv[1], reverse=reverse)
    pos = [k for k, _ in items].index(key) + 1
    return pos, len(items), [v for _, v in items]


S = norm(TARGET)
out = ["# Sunnyside vs. the district: rankings",
       "", "Generated by `scripts/sunnyside_rankings.py` from PPS documents in this folder. Rank 1 = highest.", ""]

# Utilization
u = util[S]
tot_enr = sum(v["enr"] for v in util.values()); tot_cap = sum(v["cap"] for v in util.values())
r_all = rank(util, S, lambda v: v["pct"])
nonhs = lambda k: util[k]["type"] in ("K-5", "K-8", "PK-8", "MS", "2-8")
r_nonhs = rank(util, S, lambda v: v["pct"], filt=nonhs)
k8 = lambda k: util[k]["type"] in ("K-8", "PK-8")
r_k8 = rank(util, S, lambda v: v["pct"], filt=k8)
over85 = sum(1 for v in util.values() if v["pct"] >= 85)
out += ["## Building utilization (2025-26)", "",
        f"- Sunnyside: **{u['pct']}%** ({u['enr']} students / {u['cap']} seats).",
        f"- District overall: **{100*tot_enr/tot_cap:.0f}%** ({tot_enr:,} / {tot_cap:,}); median school {statistics.median(v['pct'] for v in util.values()):.0f}%.",
        f"- Rank: **{r_all[0]} of {r_all[1]}** schools; **{r_nonhs[0]} of {r_nonhs[1]}** non-high schools; **{r_k8[0]} of {r_k8[1]}** K-8s.",
        f"- Schools at 85% or more: {over85} of {len(util)}.",
        (lambda r: f"- Among schools with a neighborhood attendance area (excluding lottery-only focus/alternative schools), non-high: **{r[0]} of {r[1]}**.")(
            rank(util, S, lambda v: v["pct"], filt=lambda k: nonhs(k) and util[k]["program"].startswith("Neighborhood"))),
        "- Most-utilized non-high schools: " + ", ".join(f"{util[k]['name']} {util[k]['pct']}%" for k, _ in sorted(((k, util[k]['pct']) for k in util if nonhs(k)), key=lambda kv: -kv[1])[:8]),
        ""]

# Enrollment trend
if S in hist:
    name, v = hist[S]
    def chg(vals, a, b):
        return 100 * (vals[b] - vals[a]) / vals[a]
    ch2 = {k: chg(x[1], 7, 9) for k, x in hist.items() if x[1][7] > 0}
    ch10 = {k: chg(x[1], 0, 9) for k, x in hist.items() if x[1][0] > 0}
    r2 = sorted(ch2.items(), key=lambda kv: -kv[1]); p2 = [k for k, _ in r2].index(S) + 1
    r10 = sorted(ch10.items(), key=lambda kv: -kv[1]); p10 = [k for k, _ in r10].index(S) + 1
    grew2 = sum(1 for x in ch2.values() if x > 0)
    out += ["## Enrollment trend", "",
            f"- Sunnyside: {v[0]} (2016-17) → {v[7]} (2023-24) → {v[8]} → **{v[9]}** (2025-26).",
            f"- Last two years: Sunnyside **{ch2[S]:+.1f}%**; district **{chg(district_hist, 7, 9):+.1f}%**. Rank **{p2} of {len(ch2)}** schools; only {grew2} of {len(ch2)} grew at all.",
            f"- Ten years: Sunnyside {ch10[S]:+.1f}%; district {chg(district_hist, 0, 9):+.1f}%. Rank {p10} of {len(ch10)}.",
            ""]

# Forecast
if S in fc:
    name, typ, v = fc[S]
    ch = {k: 100 * (x[2][12] - x[2][2]) / x[2][2] for k, x in fc.items() if x[2][2] > 0}
    r = sorted(ch.items(), key=lambda kv: -kv[1]); p = [k for k, _ in r].index(S) + 1
    tot25 = sum(x[2][2] for x in fc.values()); tot35 = sum(x[2][12] for x in fc.values())
    held = sum(1 for x in ch.values() if x >= -5)
    out += ["## PSU forecast (2026 edition, status quo)", "",
            f"- Sunnyside: {v[2]} (2025-26) → {v[8]} (2031-32) → **{v[12]}** (2035-36), **{ch[S]:+.1f}%**.",
            f"- All schools in the forecast combined: {tot25:,} → {tot35:,} ({100*(tot35-tot25)/tot25:+.1f}%). Median school {statistics.median(ch.values()):+.1f}%.",
            f"- Rank **{p} of {len(ch)}** by projected change; {held} of {len(ch)} schools are projected to lose 5% or less.",
            ""]

# Capture rate
if S in capture:
    rc = sorted(capture.items(), key=lambda kv: -kv[1][1]); pc = [k for k, _ in rc].index(S) + 1
    out += ["## Neighborhood capture rate (share of resident K-12 students who attend their neighborhood school, Oct 2025)", "",
            f"- Sunnyside: **{capture[S][1]}%**; median neighborhood {statistics.median(x[1] for x in capture.values()):.0f}%.",
            f"- Rank **{pc} of {len(capture)}** neighborhoods.",
            ""]

# Special education
if S in sped:
    elem = {k: v for k, v in sped.items() if k in util and util[k]["type"] in ("K-5", "K-8", "PK-8")}
    pos, n, vals = rank(elem, S, lambda v: v[3])
    out += ["## Special-education share (Oct 2025)", "",
            f"- Sunnyside: **{sped[S][3]}%**; median K-5/K-8 school {statistics.median(vals):.1f}%.",
            f"- Rank **{pos} of {n}** K-5 and K-8 schools. Direct certification (poverty proxy): {sped[S][2]}%.",
            ""]

# Cost per student
if S in cost:
    k8c = {k: v for k, v in cost.items() if k in util and util[k]["type"] in ("K-8", "PK-8")}
    allc = [v[1] for v in cost.values()]
    out += ["## School-level dollars per student (latest year in 2027 school reports)", "",
            f"- Sunnyside: **${cost[S][1]:,}**; median school ${statistics.median(allc):,.0f}; median K-8 ${statistics.median(v[1] for v in k8c.values()):,.0f}.",
            (lambda r: f"- Rank **{r[0]} of {r[1]}** from least to most expensive per student.")(rank(cost, S, lambda v: v[1], reverse=False)),
            ""]

open(P("SUNNYSIDE_RANKINGS.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
print(f"\n[parsed: util {len(util)}, capture {len(capture)}, hist {len(hist)}, forecast {len(fc)}, sped {len(sped)}, cost {len(cost)}]")
